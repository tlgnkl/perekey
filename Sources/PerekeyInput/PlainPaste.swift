import PerekeyCore

/// "Paste without formatting": puts only the plain text on the pasteboard,
/// posts ⌘V, and puts everything back a moment later. `paste(text:)` does the
/// same with text that is not on the pasteboard, for dictation.
///
/// Main thread only (the pasteboard is not for the event tap thread). The
/// user's pasteboard is never lost:
/// - the snapshot holds every item with every type, as bytes;
/// - the plain text is marked transient, so clipboard managers skip it;
/// - the snapshot comes back only if nobody wrote to the pasteboard since:
///   a copy the user made in the meantime wins;
/// - a second paste before the restore keeps the first snapshot, since the
///   pasteboard holds Perekey's own text by then;
/// - a password (a concealed snapshot) is not put back, so the password
///   manager's own clearing still has the last word;
/// - Perekey's own text stays on this Mac (`.currentHostOnly`), out of
///   Universal Clipboard.
@MainActor
public final class PlainPaste {
    /// nspasteboard.org conventions: managers like Maccy and Alfred skip these.
    public nonisolated static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public nonisolated static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// Set by password managers on a copied password.
    public nonisolated static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    /// Every item of a pasteboard with every type, as bytes.
    public struct Snapshot: Equatable, Sendable {
        public struct Entry: Equatable, Sendable {
            public var type: String
            public var data: Data
        }

        public var items: [[Entry]]

        /// A password. Password managers clear the pasteboard after a while,
        /// but only if its change count did not move; a restore would move it
        /// and keep the password forever. Such a snapshot is not put back: the
        /// pasteboard is left empty. Transient and auto-generated contents
        /// (TextExpander, Raycast) are put back as anything else.
        public var isConcealed: Bool {
            items.contains { $0.contains { $0.type == PlainPaste.concealedType.rawValue } }
        }

        public var byteCount: Int { items.reduce(0) { $0 + $1.reduce(0) { $0 + $1.data.count } } }
    }

    private let pasteboard: any PasteboardStore
    private let restoreDelay: Duration
    private let post: @MainActor () -> Void
    private var saved: Snapshot?
    /// The change count right after Perekey wrote the plain text.
    private var ownChangeCount = 0
    private var restoreTask: Task<Void, Never>?
    private let log = Logger(subsystem: "app.perekey", category: "paste")

    /// - Parameters:
    ///   - pasteboard: `.general` in the app; a named one or a fake in tests.
    ///   - restoreDelay: how long the target app gets to read the plain text.
    ///   - post: posts ⌘V (`postCommandV(keyCode:)` for the real one).
    public init(pasteboard: any PasteboardStore = NSPasteboard.general, restoreDelay: Duration = .milliseconds(600),
                post: @escaping @MainActor () -> Void)
    {
        self.pasteboard = pasteboard
        self.restoreDelay = restoreDelay
        self.post = post
    }

    /// Whether a restore is waiting.
    public var isRestorePending: Bool { saved != nil }

    /// Pastes the plain text of the pasteboard. `false` if it holds no text:
    /// nothing is touched then.
    @discardableResult
    public func paste() -> Bool {
        guard let text = pasteboard.plainString, !text.isEmpty else { return false }
        write(text)
        post()
        scheduleRestore(after: restoreDelay)
        return true
    }

    /// Pastes `text`, which need not be on the pasteboard: the pasteboard is
    /// saved, holds `text` while ⌘V is posted, and comes back after
    /// `restoreDelay` (the one of `init` if nil), as for `paste()`. Empty text
    /// touches nothing.
    ///
    /// The caller checks the target, Secure Input and held modifiers first
    /// (`TextPaster`); this is the pasteboard part only.
    @discardableResult
    public func paste(text: String, restoreDelay: Duration? = nil) -> Bool {
        guard !text.isEmpty else { return false }
        write(text)
        post()
        scheduleRestore(after: restoreDelay ?? self.restoreDelay)
        return true
    }

    /// As `paste(text:)`, but `post` replaces ⌘V and may fail, e.g. a press of
    /// the app's Paste menu item. The restore waits for `post`. Certainly not
    /// posted: the pasteboard comes back at once, if it still holds the text
    /// this call wrote (a "Paste without formatting" meanwhile has its own
    /// restore). Unknown (the app did not answer): the post may still arrive,
    /// so the restore waits `restoreDelay` as after a success. Empty text
    /// touches nothing and is `.notDone`.
    public func paste(text: String, restoreDelay: Duration? = nil,
                      post: @MainActor () async -> AXActionOutcome) async -> AXActionOutcome
    {
        guard !text.isEmpty else { return .notDone }
        let written = write(text)
        let outcome = await post()
        if outcome == .notDone {
            if pasteboard.changeCount == written {
                restoreNow()
            } else if pasteboard.changeCount != ownChangeCount {
                // The user copied meanwhile: their copy wins, the snapshot is stale.
                saved = nil
            }
        } else {
            scheduleRestore(after: restoreDelay ?? self.restoreDelay)
        }
        return outcome
    }

    /// Saves the pasteboard unless a pending snapshot is still the user's, and
    /// writes `text`. A pending restore is cancelled: the new one is scheduled
    /// after the post. Returns the change count of the write.
    @discardableResult
    private func write(_ text: String) -> Int {
        restoreTask?.cancel()
        restoreTask = nil
        // A pending snapshot is still the user's, unless they copied since.
        if saved == nil || pasteboard.changeCount != ownChangeCount {
            let clock = ContinuousClock()
            let start = clock.now
            let snapshot = pasteboard.snapshot()
            let elapsed = (clock.now - start).components
            let milliseconds = Double(elapsed.seconds) * 1000 + Double(elapsed.attoseconds) / 1e15
            // Sizes and time only: never the contents.
            log.info("Pasteboard snapshot: \(snapshot.items.count) items, \(snapshot.byteCount) bytes, \(milliseconds, format: .fixed(precision: 1)) ms")
            saved = snapshot
        }
        ownChangeCount = pasteboard.writePlain(text)
        return ownChangeCount
    }

    private func scheduleRestore(after delay: Duration) {
        restoreTask?.cancel()
        restoreTask = Task { [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled else { return }
            self?.restoreNow()
        }
    }

    /// Puts the snapshot back now, if the pasteboard still holds Perekey's
    /// text. A concealed snapshot (a password) is not put back: the
    /// pasteboard is emptied instead.
    public func restoreNow() {
        restoreTask?.cancel()
        restoreTask = nil
        guard let snapshot = saved else { return }
        saved = nil
        guard pasteboard.changeCount == ownChangeCount else { return }
        pasteboard.restore(snapshot.isConcealed ? Snapshot(items: []) : snapshot)
    }

    // MARK: - Pasteboard

    public static func plainString(of pasteboard: NSPasteboard) -> String? {
        pasteboard.string(forType: .string)
    }

    public static func snapshot(of pasteboard: NSPasteboard) -> Snapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type -> Snapshot.Entry? in
                item.data(forType: type).map { Snapshot.Entry(type: type.rawValue, data: $0) }
            }
        }
        return Snapshot(items: items.filter { !$0.isEmpty })
    }

    /// Replaces the contents with `text` only, marked transient. Returns the
    /// new change count. This Mac only: Universal Clipboard would carry the
    /// text to the user's iPhone and iPad.
    @discardableResult
    public static func writePlain(_ text: String, to pasteboard: NSPasteboard) -> Int {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Puts `snapshot` back. An empty snapshot leaves the pasteboard empty.
    /// Unlike `writePlain`, with the usual options: this is the user's own
    /// copy, already on their other devices through Universal Clipboard, and
    /// this Mac only would take it from their iPhone.
    @discardableResult
    public static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let items = snapshot.items.map { entries in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type)) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        return pasteboard.changeCount
    }

    // MARK: - ⌘V

    /// Posts ⌘V on `keyCode`, marked as Perekey's own so the tap lets it through.
    /// `seq` 0 is never a fence's.
    public static func postCommandV(keyCode: UInt16) {
        let source = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: down) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData,
                                       value: SyntheticMark.own(seq: 0, last: !down).userData)
            event.post(tap: .cghidEventTap)
        }
    }
}

/// The few pasteboard operations `PlainPaste` needs, so tests can count and
/// fail them. `NSPasteboard` is the real one.
@MainActor
public protocol PasteboardStore: AnyObject {
    /// Grows on every write by anyone; tells whether the contents are still ours.
    var changeCount: Int { get }
    var plainString: String? { get }
    func snapshot() -> PlainPaste.Snapshot
    /// Replaces the contents with `text`, marked transient; the new change count.
    @discardableResult func writePlain(_ text: String) -> Int
    @discardableResult func restore(_ snapshot: PlainPaste.Snapshot) -> Int
}

extension NSPasteboard: PasteboardStore {
    public var plainString: String? { PlainPaste.plainString(of: self) }
    public func snapshot() -> PlainPaste.Snapshot { PlainPaste.snapshot(of: self) }
    @discardableResult public func writePlain(_ text: String) -> Int { PlainPaste.writePlain(text, to: self) }
    @discardableResult public func restore(_ snapshot: PlainPaste.Snapshot) -> Int {
        PlainPaste.restore(snapshot, to: self)
    }
}
